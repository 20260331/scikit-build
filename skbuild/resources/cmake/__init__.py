def _validate_module_filename(name: str) -> None:
    if not name.endswith(_MODULE_SUFFIX) or not _SAFE_NAME_RE.fullmatch(name) or name in {".", ".."}:
        msg = f"invalid CMake module name {name!r}: expected a single safe path component ending in '.cmake'"
        raise InvalidModuleNameError(msg)


def _resolve_root(source: str | os.PathLike[str] | Traversable | None) -> Traversable:
    """Resolve the user supplied ``source`` to a resource traversable."""
    if source is None:
        return importlib.resources.files(importlib.import_module(RESOURCE_PACKAGE))
    if isinstance(source, (str, os.PathLike)):
        text = os.fspath(source)
        if os.path.isdir(text):
            return Path(text)
        try:
            module = importlib.import_module(text)
        except ModuleNotFoundError as exc:
            msg = f"resource source {text!r} is neither an importable package nor an existing directory"
            raise BundleError(msg) from exc
        return importlib.resources.files(module)
    return source


@dataclass(frozen=True)
class ModuleGraph:
    """Static dependency graph of the CMake modules in a resource set."""

    modules: tuple[str, ...]
    files: Mapping[str, str]
    resources: Mapping[str, Traversable]
    edges: tuple[DependencyEdge, ...]

    def resolve(self, name: str) -> str:
        """Resolve a request (``"FindCython"`` or the package ``"Cython"``)."""
        if not _SAFE_NAME_RE.fullmatch(name):
            msg = f"invalid module request {name!r}: expected a safe module name"
            raise InvalidModuleNameError(msg)
        stems = self.modules
        if name in stems:
            return name
        find_name = "Find" + name
        if find_name in stems:
            return find_name
        folded = {name.casefold(), find_name.casefold()}
        case_matches = sorted(module for module in stems if module.casefold() in folded)
        if case_matches:
            msg = f"module request {name!r} only matches {case_matches} case-insensitively; use the exact name"
            raise ModuleNameCollisionError(msg)
        available = ", ".join(stems)
        msg = f"unknown CMake module {name!r}. Available modules: {available}"
        raise UnknownModuleError(msg)

    def internal_edges(self, node: str) -> tuple[str, ...]:
        return tuple(
            sorted(
                edge.node
                for edge in self.edges
                if edge.source == node and edge.status == "internal" and edge.node is not None
            )
        )

    def closure(self, requested: str | Iterable[str]) -> tuple[str, ...]:
        """Return the sorted, de-duplicated internal dependency closure."""
        names = (requested,) if isinstance(requested, str) else tuple(requested)
        roots = [self.resolve(name) for name in names]
        seen: set[str] = set()
        stack = list(dict.fromkeys(roots))
        while stack:
            node = stack.pop()
            if node in seen:
                continue
            seen.add(node)
            stack.extend(reversed(self.internal_edges(node)))
        return tuple(sorted(seen))

    def cycles(self, nodes: Iterable[str] | None = None) -> tuple[tuple[str, ...], ...]:
        """Return strongly connected components of size > 1 (and self loops)."""
        allowed = set(self.modules if nodes is None else list(nodes))
        adjacency: dict[str, list[str]] = {}
        for node in allowed:
            adjacency[node] = [
                edge.node
                for edge in self.edges
                if edge.source == node and edge.status == "internal" and edge.node is not None and edge.node in allowed
            ]
        index = 0
        indices: dict[str, int] = {}
        lowlink: dict[str, int] = {}
        stack: list[str] = []
        on_stack: set[str] = set()
        cycles: list[tuple[str, ...]] = []

        def strongconnect(v: str) -> None:
            nonlocal index
            indices[v] = index
            lowlink[v] = index
            index += 1
            stack.append(v)
            on_stack.add(v)
            for w in adjacency[v]:
                if w not in indices:
                    strongconnect(w)
                    lowlink[v] = min(lowlink[v], lowlink[w])
                elif w in on_stack:
                    lowlink[v] = min(lowlink[v], indices[w])
            if lowlink[v] == indices[v]:
                component: list[str] = []
                while True:
                    w = stack.pop()
                    on_stack.remove(w)
                    component.append(w)
                    if w == v:
                        break
                if len(component) > 1 or v in adjacency[v]:
                    cycles.append(tuple(sorted(component)))

        for node in sorted(allowed):
            if node not in indices:
                strongconnect(node)
        return tuple(sorted(cycles))


def _classify(dep: Dependency, source: str, stems: set[str]) -> DependencyEdge:
    if dep.dynamic:
        return DependencyEdge(source, dep.name, dep.kind, "unresolved", None)
    name = dep.name
    if dep.kind == "find_package":
        if _SAFE_NAME_RE.fullmatch(name):
            node = "Find" + name
            if node in stems:
                return DependencyEdge(source, name, dep.kind, "internal", node)
        return DependencyEdge(source, name, dep.kind, "external", None)
    # include(): a bare module name or a file path ending in .cmake.
    base = name.replace("\\", "/").rstrip("/").split("/")[-1].removesuffix(_MODULE_SUFFIX)
    if base and _SAFE_NAME_RE.fullmatch(base) and base in stems:
        return DependencyEdge(source, name, dep.kind, "internal", base)
    return DependencyEdge(source, name, dep.kind, "external", None)


def build_graph(source: str | os.PathLike[str] | Traversable | None = None) -> ModuleGraph:
    """Build the static dependency graph of the resource modules.

    ``source`` may be ``None`` (the shipped ``skbuild.resources.cmake``
    package), an importable package name, a filesystem directory, or any
    :class:`~importlib.resources.Traversable` (e.g. a directory inside a zip).
    """
    root = _resolve_root(source)

    files: dict[str, str] = {}
    resources: dict[str, Traversable] = {}
    seen_folds: dict[str, str] = {}
    for child in sorted(root.iterdir(), key=lambda entry: entry.name):
        name = child.name
        if not name.endswith(_MODULE_SUFFIX) or not child.is_file():
            continue
        _validate_module_filename(name)
        if name == ENTRY_FILENAME:
            msg = f"resource {name!r} clashes with the generated bundle entry point"
            raise InvalidModuleNameError(msg)
        folded = name.casefold()
        if folded in seen_folds:
            msg = f"module names {seen_folds[folded]!r} and {name!r} differ only in case"
            raise ModuleNameCollisionError(msg)
        seen_folds[folded] = name
        stem = name[: -len(_MODULE_SUFFIX)]
        files[stem] = name
        resources[stem] = child

    stems = set(files)
    edges: list[DependencyEdge] = []
    for stem in sorted(files):
        try:
            text = resources[stem].read_bytes().decode("utf-8")
        except UnicodeDecodeError as exc:
            msg = f"CMake module {files[stem]!r} is not valid UTF-8: {exc}"
            raise BundleError(msg) from exc
        for dep in parse_dependencies(text):
            edges.append(_classify(dep, stem, stems))

    return ModuleGraph(tuple(sorted(files)), dict(sorted(files.items())), dict(sorted(resources.items())), tuple(edges))


def dependency_closure(graph: ModuleGraph, requested: str | Iterable[str]) -> tuple[str, ...]:
    """Resolve requested module names and return their dependency closure."""
    return graph.closure(requested)


