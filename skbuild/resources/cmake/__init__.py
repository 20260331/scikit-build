def _generator_version() -> str:
    try:
        return metadata.version("scikit-build")
    except metadata.PackageNotFoundError:
        return "0.0.0"


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _build_manifest(
    graph: ModuleGraph,
    roots: Sequence[str],
    closure_nodes: Sequence[str],
    file_hashes: Mapping[str, str],
) -> dict[str, Any]:
    allowed = set(closure_nodes)
    edges = [
        {"source": edge.source, "target": edge.target, "kind": edge.kind, "status": edge.status}
        for edge in graph.edges
        if edge.source in allowed
    ]
    edges.sort(key=lambda edge: (edge["source"], edge["target"], edge["kind"], edge["status"]))
    return {
        "bundle_format": BUNDLE_FORMAT_VERSION,
        "generator": "scikit-build",
        "generator_version": _generator_version(),
        "entry": ENTRY_FILENAME,
        "requested": sorted(roots),
        "modules": list(closure_nodes),
        "files": [{"path": path, "sha256": digest} for path, digest in sorted(file_hashes.items())],
        "edges": edges,
        "cycles": [list(cycle) for cycle in graph.cycles(allowed)],
    }


def _render_manifest(manifest: Mapping[str, Any]) -> bytes:
    return (json.dumps(manifest, sort_keys=True, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def _unique_sibling(destination: Path, prefix: str) -> Path:
    token = tempfile.mkdtemp(prefix=prefix, dir=str(destination.parent))
    shutil.rmtree(token)
    return Path(token)


def _walk_regular_files(directory: Path) -> tuple[dict[str, Path], list[tuple[str, Path]]]:
    """Return (relative regular files, symlinks) under ``directory``.

    Symlinks (to files or directories) are reported and never followed.
    """
    regular: dict[str, Path] = {}
    symlinks: list[tuple[str, Path]] = []

    def walk(current: Path, prefix: str) -> None:
        with os.scandir(current) as scan:
            entries = sorted(scan, key=lambda entry: entry.name)
        for entry in entries:
            relative = f"{prefix}{entry.name}" if prefix else entry.name
            if entry.is_symlink():
                symlinks.append((relative, Path(entry.path)))
                continue
            if entry.is_dir(follow_symlinks=False):
                walk(Path(entry.path), f"{relative}/")
            elif entry.is_file(follow_symlinks=False):
                regular[relative] = Path(entry.path)

    walk(directory, "")
    return regular, symlinks


def _same_content(destination: Path, expected: Mapping[str, bytes]) -> bool:
    """True when ``destination`` is an existing bundle byte-identical to expected."""
    if destination.is_symlink() or not destination.is_dir():
        return False
    manifest_path = destination / MANIFEST_FILENAME
    if manifest_path.is_symlink() or not manifest_path.is_file():
        return False
    try:
        actual, symlinks = _walk_regular_files(destination)
    except OSError:
        return False
    if symlinks or set(actual) != set(expected):
        return False
    return all(path.read_bytes() == expected[relative] for relative, path in actual.items())


def export_bundle(
    modules: str | Iterable[str],
    destination: str | os.PathLike[str],
    *,
    source: str | os.PathLike[str] | Traversable | None = None,
    overwrite: bool = False,
) -> Path:
    """Export a relocatable, checksummed CMake module bundle.

    Arguments:
        modules: module stems (``"FindCython"``) or package names
            (``"Cython"``); the full static ``include()``/``find_package()``
            closure is collected, each file only once.
        destination: directory to write the bundle into.  It must not exist
            unless it already contains a byte-identical bundle; with
            ``overwrite=True`` an existing bundle directory is replaced
            atomically.  A non-bundle directory or file is never overwritten.
        source: resource set to export from (see :func:`build_graph`).
        overwrite: replace an existing, differing bundle directory.

    Unknown modules, path-traversal names and case-only collisions are
    rejected *before* ``destination`` is touched.  Failures never leave a
    half-written destination behind.
    """
    dest = Path(os.fspath(destination))
    graph = build_graph(source)

    names = (modules,) if isinstance(modules, str) else tuple(modules)
    if not names:
        msg = "at least one module must be requested"
        raise BundleError(msg)
    roots = [graph.resolve(name) for name in names]
    closure_nodes = graph.closure(roots)

    unresolved = sorted(
        {edge.target for edge in graph.edges if edge.source in set(closure_nodes) and edge.status == "unresolved"}
    )
    if unresolved:
        msg = f"cannot bundle {sorted(closure_nodes)}: unresolved dynamic dependencies: {unresolved}"
        raise BundleError(msg)

    payload: dict[str, bytes] = {}
    for stem in closure_nodes:
        payload[graph.files[stem]] = graph.resources[stem].read_bytes()
    payload[ENTRY_FILENAME] = _ENTRY_CMAKE.encode("utf-8")

    manifest = _build_manifest(graph, roots, closure_nodes, {name: _sha256(data) for name, data in payload.items()})
    manifest_bytes = _render_manifest(manifest)
    payload[MANIFEST_FILENAME] = manifest_bytes

    if os.path.lexists(dest):
        if _same_content(dest, payload):
            return dest
        if not overwrite:
            msg = (
                f"{dest} already exists and is not a byte-identical bundle; refusing to overwrite "
                "(pass overwrite=True to replace an existing bundle directory)"
            )
            raise BundleExistsError(msg)
        if dest.is_symlink() or not dest.is_dir():
            msg = f"{dest} exists and is not a bundle directory; refusing to overwrite"
            raise BundleExistsError(msg)

    dest.parent.mkdir(parents=True, exist_ok=True)
    stage = _unique_sibling(dest, ".skbuild-bundle.")
    try:
        stage.mkdir()
        # Resource names were validated when the graph was built, and the
        # entry/manifest names are trusted constants, so payload keys are safe.
        for name, data in payload.items():
            (stage / name).write_bytes(data)
        report = verify_bundle(stage)
        if not report.ok:
            details = "; ".join(problem.message for problem in report.problems)
            msg = f"freshly staged bundle failed verification: {details}"
            raise BundleVerificationError(msg)

        if os.path.lexists(dest) and overwrite:
            backup = _unique_sibling(dest, ".skbuild-bundle.old.")
            os.rename(dest, backup)
            try:
                os.replace(stage, dest)
            except OSError:
                os.replace(backup, dest)
                raise
            shutil.rmtree(backup, ignore_errors=True)
        else:
            os.replace(stage, dest)
    except BaseException:
        shutil.rmtree(stage, ignore_errors=True)
        raise
    return dest


