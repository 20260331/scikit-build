"""
Relocatable CMake module bundle export.

The ``.cmake`` files in this package are the historical scikit-build CMake
helpers (``FindCython``, ``UseCython``, ...). scikit-build-core registers the
package directory through the ``cmake.module`` entry point so that
``CMAKE_MODULE_PATH`` points straight at ``site-packages``.  Projects that
wish to keep building offline -- or on a machine without scikit-build
installed -- can instead :func:`export_bundle` a selected set of modules.

The export computes the *static* ``include()``/``find_package()`` dependency
closure of the requested modules, writes the files and a checksummed manifest
into a destination directory, and adds a relocatable CMake entry point.  The
resulting bundle can be moved: the entry point derives the module path from
``CMAKE_CURRENT_LIST_DIR`` and never embeds an absolute host path.

Resources are read through :class:`importlib.resources.Traversable`, so the
same API works for a regular installation, an editable checkout and a
zip-imported package.
"""

