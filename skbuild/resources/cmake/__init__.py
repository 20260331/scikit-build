import argparse
import hashlib
import importlib
import importlib.resources
import importlib.util
import json
import os
import re
import shutil
import sys
import tempfile
from collections.abc import Iterable, Iterator, Mapping, Sequence
from dataclasses import dataclass
from importlib import metadata
from pathlib import Path
from typing import TYPE_CHECKING, Any

from ...exceptions import (
    BundleError,
    BundleExistsError,
    BundleVerificationError,
    InvalidModuleNameError,
    ModuleNameCollisionError,
    UnknownModuleError,
)

if TYPE_CHECKING:
    from typing import Protocol

    class Traversable(Protocol):
        """Structural type for :func:`importlib.resources.files` results.

        ``pathlib.Path`` and the in-zip/in-multiplexed resource traversables
        all satisfy it, so the API does not require a real filesystem path.
        """

        @property
        def name(self) -> str: ...

        def iterdir(self) -> Iterable[Traversable]: ...

        def is_file(self) -> bool: ...

        def is_dir(self) -> bool: ...

        def read_bytes(self) -> bytes: ...


