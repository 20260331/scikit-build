#: Name of the package that ships the historical CMake helper modules.
RESOURCE_PACKAGE = "skbuild.resources.cmake"

#: Version of the on-disk bundle layout / manifest schema.
BUNDLE_FORMAT_VERSION = 1

#: Manifest file written into every bundle.
MANIFEST_FILENAME = "skbuild-bundle-manifest.json"

#: Relocatable CMake entry point written into every bundle.
ENTRY_FILENAME = "skbuild-bundle.cmake"

_MODULE_SUFFIX = ".cmake"

# A safe, single path component: alnum/underscore first, then alnum, dot,
# underscore, plus and minus.  Everything that could traverse directories or
# smuggle a separator is rejected before anything is written.
_SAFE_NAME_RE = re.compile(r"^[A-Za-z0-9_][A-Za-z0-9_.+\-]*$")
_SHA256_RE = re.compile(r"^[0-9a-f]{64}$")
_COMMAND_NAME_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
# ${...} variables, $<...> generator expressions and @...@ configure
# substitutions cannot be resolved statically.
_DYNAMIC_RE = re.compile(r"\$\{[^}]*\}|\$<[^>]*>|@[A-Za-z0-9_]+@")

# Entry point prepended to every bundle.  It must stay free of absolute paths
# or timestamps so that repeated exports produce identical bytes.
_ENTRY_CMAKE = """\
# Generated by scikit-build: CMake module bundle entry point.
#
# This file lives next to the bundled .cmake modules. Including it prepends
# this directory -- located through CMAKE_CURRENT_LIST_DIR, never hard-coded
# -- to CMAKE_MODULE_PATH, so the whole bundle directory can be moved or
# copied after export without regenerating it. Pre-existing CMAKE_MODULE_PATH
# entries are preserved, and duplicate entries for this directory are removed.
#
# Usage from a downstream CMakeLists.txt:
#   include(${CMAKE_CURRENT_LIST_DIR}/path/to/skbuild-bundle.cmake)
#   find_package(Cython REQUIRED)

get_filename_component(_skbuild_bundle_dir "${CMAKE_CURRENT_LIST_DIR}" ABSOLUTE)
list(REMOVE_ITEM CMAKE_MODULE_PATH "${_skbuild_bundle_dir}")
list(PREPEND CMAKE_MODULE_PATH "${_skbuild_bundle_dir}")
unset(_skbuild_bundle_dir)
"""


