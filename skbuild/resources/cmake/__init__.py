@dataclass(frozen=True)
class BundleProblem:
    """One integrity problem found by :func:`verify_bundle`."""

    code: str
    path: str | None
    message: str


@dataclass(frozen=True)
class BundleVerificationReport:
    """Result of :func:`verify_bundle`; boolean value is :attr:`ok`."""

    ok: bool
    destination: Path
    problems: tuple[BundleProblem, ...]
    manifest: dict[str, Any] | None

    def __bool__(self) -> bool:
        return self.ok

    def raise_if_invalid(self) -> None:
        if not self.ok:
            details = "; ".join(problem.message for problem in self.problems)
            msg = f"bundle at {self.destination} failed verification: {details}"
            raise BundleVerificationError(msg)


def _validate_manifest_path(name: str) -> None:
    if not name or "\x00" in name or "\\" in name or os.path.isabs(name) or name == MANIFEST_FILENAME:
        msg = f"illegal manifest path {name!r}"
        raise InvalidModuleNameError(msg)
    pure = Path(name)
    if pure.is_absolute() or any(part in {"", ".", ".."} for part in pure.parts):
        msg = f"illegal manifest path {name!r}"
        raise InvalidModuleNameError(msg)
    if not _SAFE_NAME_RE.fullmatch(name):
        msg = f"illegal manifest path {name!r}"
        raise InvalidModuleNameError(msg)


def _parse_manifest(raw: bytes) -> tuple[dict[str, Any] | None, list[BundleProblem]]:
    problems: list[BundleProblem] = []
    try:
        manifest = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        return None, [BundleProblem("malformed_manifest", MANIFEST_FILENAME, f"manifest is not valid JSON: {exc}")]
    if not isinstance(manifest, dict):
        return None, [BundleProblem("malformed_manifest", MANIFEST_FILENAME, "manifest must be a JSON object")]
    if manifest.get("bundle_format") != BUNDLE_FORMAT_VERSION:
        problems.append(
            BundleProblem(
                "malformed_manifest",
                MANIFEST_FILENAME,
                f"unsupported bundle_format {manifest.get('bundle_format')!r}; expected {BUNDLE_FORMAT_VERSION}",
            )
        )
    files = manifest.get("files")
    if not isinstance(files, list):
        problems.append(BundleProblem("malformed_manifest", MANIFEST_FILENAME, "manifest 'files' must be a list"))
        return manifest, problems
    seen: set[str] = set()
    for record in files:
        if not isinstance(record, dict):
            problems.append(
                BundleProblem("malformed_manifest", MANIFEST_FILENAME, f"file record must be an object: {record!r}")
            )
            continue
        path = record.get("path")
        digest = record.get("sha256")
        if not isinstance(path, str):
            problems.append(BundleProblem("malformed_manifest", MANIFEST_FILENAME, f"missing file path: {record!r}"))
            continue
        if path in seen:
            problems.append(BundleProblem("illegal_manifest_path", path, f"duplicate path in manifest: {path!r}"))
            continue
        seen.add(path)
        try:
            _validate_manifest_path(path)
        except InvalidModuleNameError:
            problems.append(BundleProblem("illegal_manifest_path", path, f"unsafe path in manifest: {path!r}"))
        if not isinstance(digest, str) or not _SHA256_RE.fullmatch(digest):
            problems.append(BundleProblem("malformed_manifest", path, f"invalid sha256 for {path!r}: {digest!r}"))
    return manifest, problems


def verify_bundle(destination: str | os.PathLike[str], *, strict: bool = False) -> BundleVerificationReport:
    """Verify a bundle directory against its checksum manifest.

    Detects modified files (hash mismatch), missing and extra files,
    symlinks, malformed manifests and illegal (absolute / traversal) manifest
    paths.  Returns a :class:`BundleVerificationReport`; pass ``strict=True``
    to raise :class:`BundleVerificationError` on the first failed bundle.
    """
    dest = Path(os.fspath(destination))
    problems: list[BundleProblem] = []

    if not os.path.exists(dest) or not dest.is_dir() or dest.is_symlink():
        problems.append(BundleProblem("not_a_directory", None, f"{dest} is not a bundle directory"))
        report = BundleVerificationReport(False, dest, tuple(problems), None)
        if strict:
            report.raise_if_invalid()
        return report

    actual, symlinks = _walk_regular_files(dest)
    for relative, path in symlinks:
        problems.append(BundleProblem("symlink", relative, f"symlinks are not allowed in bundles: {path}"))

    manifest_path = dest / MANIFEST_FILENAME
    if manifest_path.is_symlink() or not manifest_path.is_file():
        problems.append(BundleProblem("missing_manifest", MANIFEST_FILENAME, f"manifest not found: {manifest_path}"))
        report = BundleVerificationReport(False, dest, tuple(problems), None)
        if strict:
            report.raise_if_invalid()
        return report

    manifest, manifest_problems = _parse_manifest(manifest_path.read_bytes())
    problems.extend(manifest_problems)

    expected: dict[str, str] = {}
    if isinstance(manifest, dict) and isinstance(manifest.get("files"), list):
        for record in manifest["files"]:
            if not isinstance(record, dict):
                continue
            record_path = record.get("path")
            record_digest = record.get("sha256")
            if not isinstance(record_path, str) or not isinstance(record_digest, str):
                continue
            if not _SHA256_RE.fullmatch(record_digest):
                continue
            try:
                _validate_manifest_path(record_path)
            except InvalidModuleNameError:
                # Reported as an illegal_manifest_path problem above; do not
                # cascade into missing/hash checks for unsafe names.
                continue
            expected[record_path] = record_digest

    for relative in sorted(set(expected) - set(actual)):
        problems.append(BundleProblem("missing_file", relative, f"file listed in manifest is missing: {relative}"))
    for relative in sorted(set(actual) - set(expected) - {MANIFEST_FILENAME}):
        problems.append(BundleProblem("extra_file", relative, f"file not listed in manifest: {relative}"))
    for relative in sorted(set(expected) & set(actual)):
        digest = hashlib.sha256()
        with actual[relative].open("rb") as stream:
            for chunk in iter(lambda: stream.read(1024 * 1024), b""):
                digest.update(chunk)
        actual_digest = digest.hexdigest()
        if actual_digest != expected[relative]:
            problems.append(
                BundleProblem(
                    "hash_mismatch",
                    relative,
                    f"sha256 mismatch for {relative}: expected {expected[relative]}, got {actual_digest}",
                )
            )

    report = BundleVerificationReport(not problems, dest, tuple(problems), manifest)
    if strict:
        report.raise_if_invalid()
    return report


def load_manifest(destination: str | os.PathLike[str]) -> dict[str, Any]:
    """Load and schema-check a bundle manifest, raising on any problem."""
    report = verify_bundle(destination, strict=True)
    assert report.manifest is not None
    return report.manifest


# ---------------------------------------------------------------------------
# Command line: ``python -m skbuild.resources.cmake ...``
# ---------------------------------------------------------------------------


def _cli_export(args: Any) -> int:
    try:
        dest = export_bundle(args.modules, args.destination, source=args.source, overwrite=args.overwrite)
        manifest = json.loads((dest / MANIFEST_FILENAME).read_text(encoding="utf-8"))
        report = verify_bundle(dest)
    except (BundleError, OSError, json.JSONDecodeError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    print(f"exported {len(manifest['modules'])} module(s) to {dest}")
    return 0 if report.ok else 1


def _cli_verify(args: Any) -> int:
    report = verify_bundle(args.destination)
    for problem in report.problems:
        location = f"{problem.path}: " if problem.path else ""
        print(f"{problem.code}: {location}{problem.message}", file=sys.stderr)
    if report.ok:
        print(f"{args.destination}: OK")
        return 0
    return 1


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m skbuild.resources.cmake", description="Export and verify relocatable CMake module bundles."
    )
    subparsers = parser.add_subparsers(dest="command", required=True)

    export_parser = subparsers.add_parser("export", help="export a module bundle")
    export_parser.add_argument("modules", nargs="+", help="module stems (FindCython) or package names (Cython)")
    export_parser.add_argument("-o", "--destination", required=True, help="directory to write the bundle into")
    export_parser.add_argument(
        "--source", default=None, help="importable package or directory with the .cmake resources"
    )
    export_parser.add_argument(
        "--overwrite", action="store_true", help="replace an existing, differing bundle directory"
    )
    export_parser.set_defaults(func=_cli_export)

    verify_parser = subparsers.add_parser("verify", help="verify a bundle directory")
    verify_parser.add_argument("destination", help="bundle directory")
    verify_parser.set_defaults(func=_cli_verify)

    args = parser.parse_args(argv)
    return int(args.func(args))
