@dataclass(frozen=True)
class Dependency:
    """One static ``include``/``find_package`` reference found in a module.

    ``kind`` is ``"include"`` or ``"find_package"``; ``name`` is the first
    argument exactly as written (without surrounding quotes); ``dynamic`` is
    true when the name is computed (variable, generator expression, ...) and
    cannot be resolved statically.
    """

    kind: str
    name: str
    dynamic: bool


@dataclass(frozen=True)
class DependencyEdge:
    """A resolved dependency edge between resource modules.

    ``source`` is the stem of the module containing the reference, ``target``
    is the referenced name as written, ``kind`` is ``"include"`` or
    ``"find_package"`` and ``status`` is one of:

    * ``"internal"``   -- resolved to a module shipped in the resource set;
    * ``"external"``   -- a CMake/third-party module not shipped here;
    * ``"unresolved"`` -- the name is dynamic and cannot be resolved.
    """

    source: str
    target: str
    kind: str
    status: str
    node: str | None


def _match_bracket(text: str, i: int) -> tuple[int, int, int] | None:
    """Match a CMake bracket argument/comment opening at ``text[i] == '['``.

    Returns ``(content_start, content_end, past_close)`` for ``[=*[ ... ]=*]``
    or ``None`` when no bracket starts at ``i``.
    """
    if i >= len(text) or text[i] != "[":
        return None
    j = i + 1
    equals = 0
    while j < len(text) and text[j] == "=":
        equals += 1
        j += 1
    if j >= len(text) or text[j] != "[":
        return None
    marker = "]" + "=" * equals + "]"
    end = text.find(marker, j + 1)
    if end == -1:
        return None
    return j + 1, end, end + len(marker)


def _skip_quoted(text: str, i: int) -> int:
    """Return index after the quoted argument starting at ``text[i] == '"'``."""
    n = len(text)
    j = i + 1
    while j < n:
        ch = text[j]
        if ch == "\\" and j + 1 < n:
            j += 2
            continue
        if ch == '"':
            return j + 1
        j += 1
    return n


def _parse_command_args(text: str, start: int) -> tuple[list[tuple[str, str]], int | None]:
    """Parse the argument list of a command whose ``(`` is before ``start``.

    Returns the arguments as ``(value, kind)`` tuples (kind is ``"quoted"``,
    ``"bracket"`` or ``"unquoted"``) and the index just past the matching
    ``)``.  Comments, quoted strings and bracket arguments do not count as
    nesting or command calls.
    """
    n = len(text)
    i = start
    depth = 1
    args: list[tuple[str, str]] = []
    while i < n:
        ch = text[i]
        if ch in " \t\r\n":
            i += 1
            continue
        if ch == "#":
            bracket = _match_bracket(text, i + 1)
            if bracket is not None:
                i = bracket[2]
            else:
                newline = text.find("\n", i + 1)
                i = n if newline == -1 else newline + 1
            continue
        if ch == '"':
            content_start = i + 1
            end = _skip_quoted(text, i)
            content_end = end - 1 if end < n and text[end - 1] == '"' else end
            args.append((text[content_start:content_end], "quoted"))
            i = end
            continue
        if ch == "[":
            bracket = _match_bracket(text, i)
            if bracket is not None:
                args.append((text[bracket[0] : bracket[1]], "bracket"))
                i = bracket[2]
                continue
            i += 1
            continue
        if ch == ")":
            depth -= 1
            if depth == 0:
                return args, i + 1
            i += 1
            continue
        if ch == "(":
            depth += 1
            i += 1
            continue
        j = i
        while j < n and text[j] not in ' \t\r\n()#"':
            j += 1
        args.append((text[i:j], "unquoted"))
        i = j
    return args, None


def _iter_commands(text: str) -> Iterator[tuple[str, list[tuple[str, str]]]]:
    """Yield ``(lowercase_command, arguments)`` pairs, ignoring comments/strings."""
    n = len(text)
    i = 0
    while i < n:
        ch = text[i]
        if ch == "#":
            bracket = _match_bracket(text, i + 1)
            if bracket is not None:
                i = bracket[2]
            else:
                newline = text.find("\n", i + 1)
                i = n if newline == -1 else newline + 1
            continue
        if ch == '"':
            i = _skip_quoted(text, i)
            continue
        if ch == "[":
            bracket = _match_bracket(text, i)
            if bracket is not None:
                i = bracket[2]
                continue
            i += 1
            continue
        if (ch.isascii() and ch.isalpha()) or ch == "_":
            match = _COMMAND_NAME_RE.match(text, i)
            assert match is not None
            name = match.group(0)
            j = match.end()
            k = j
            while k < n and text[k] in " \t":
                k += 1
            if k < n and text[k] == "(":
                args, end = _parse_command_args(text, k + 1)
                if end is not None:
                    yield name.lower(), args
                    i = end
                    continue
                i = n
                continue
            i = j
            continue
        i += 1


def parse_dependencies(source: str | bytes) -> tuple[Dependency, ...]:
    """Statically parse ``include()``/``find_package()`` references.

    The parse is comment/string aware: pseudo calls inside ``#`` comments,
    quoted/bracket arguments and bracket comments are ignored.  References
    whose name contains variables or generator expressions are reported as
    dynamic, never guessed.
    """
    text = source.decode("utf-8") if isinstance(source, bytes) else source
    deps: list[Dependency] = []
    for command, args in _iter_commands(text):
        if command not in {"include", "find_package"} or not args:
            continue
        value, kind = args[0]
        name = value.strip()
        dynamic = kind == "bracket" or not name or bool(_DYNAMIC_RE.search(name))
        deps.append(Dependency(command, name, dynamic))
    return tuple(deps)


